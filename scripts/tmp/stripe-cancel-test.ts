import { stripeCall } from "@/lib/billing/providers.server";
import { getBillingAdapter } from "@/lib/billing/providers.server";

const env = "test" as const;
const a = getBillingAdapter("stripe");
const prices = await stripeCall(env, "prices?active=true&type=recurring&limit=1", undefined, "GET");
const price = prices.data?.[0]?.id;
const cust = await stripeCall(env, "customers", { email: "cancel-test@munchreach.com" });
const pm = await stripeCall(env, "payment_methods", { type: "card", "card[token]": "tok_visa" });
await stripeCall(env, `payment_methods/${pm.id}/attach`, { customer: cust.id });
await stripeCall(env, `customers/${cust.id}`, { "invoice_settings[default_payment_method]": pm.id });
const sub = await stripeCall(env, "subscriptions", { customer: cust.id, "items[0][price]": price });
console.log("created", sub.id, sub.status, sub.cancel_at_period_end);
await a.cancel(env, sub.id, true);
let s = await stripeCall(env, `subscriptions/${sub.id}`, undefined, "GET");
console.log("after cancel:", s.status, "cancel_at_period_end=", s.cancel_at_period_end);
await a.resume(env, sub.id);
s = await stripeCall(env, `subscriptions/${sub.id}`, undefined, "GET");
console.log("after resume:", s.status, "cancel_at_period_end=", s.cancel_at_period_end);
await stripeCall(env, `subscriptions/${sub.id}`, undefined, "DELETE");
