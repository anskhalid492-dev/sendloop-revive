import { createDecipheriv, createHash } from 'node:crypto';
import { mapMailerooRecords, mailerooEntriesCreated, findMailerooDomain } from '../../src/lib/domain-providers/maileroo.server';
const url = process.env.SUPABASE_URL!, key = process.env.SUPABASE_SERVICE_ROLE_KEY!;
const rows = await (await fetch(`${url}/rest/v1/email_provider_secrets?select=credentials_ciphertext&provider_id=eq.7628bbd2-cb7f-46c5-ad47-e884297c96bf`, { headers: { apikey: key, Authorization: `Bearer ${key}` } })).json();
const buf = Buffer.from(rows[0].credentials_ciphertext, 'base64');
const k = createHash('sha256').update(process.env.PROVIDER_CREDENTIALS_KEY!).digest();
const d = createDecipheriv('aes-256-gcm', k, buf.subarray(0,12)); d.setAuthTag(buf.subarray(12,28));
const creds = JSON.parse(Buffer.concat([d.update(buf.subarray(28)), d.final()]).toString());
const found = await findMailerooDomain(creds, 'meetsmartoutreach.agency');
console.log(mapMailerooRecords('meetsmartoutreach.agency', found).map(r => `${r.kind} ${r.type} ${r.host} prio=${r.priority ?? '-'} ${String(r.value).slice(0,40)}`));
console.log('mx live in DNS at provider:', mailerooEntriesCreated(found?.dns_records?.['mx_record']));
